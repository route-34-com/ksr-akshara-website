"""Self-hosted fonts and a trimmed icon font, written to assets/css/vendor.css.

Run after adding new icons:  /tmp/ksrvenv/bin/python vendor_assets.py   (needs fonttools + brotli)
- Outfit and Figtree come from assets/fonts/fonts.css (downloaded once from Google Fonts).
- Phosphor (regular + fill) is cut down to only the icons the site uses, which takes
  two ~150 KB fonts down to a few KB and removes two blocking requests to a CDN.
"""
import re
import subprocess
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).parent
BASE = "https://cdn.jsdelivr.net/npm/@phosphor-icons/web@2.1.1/src"
STYLES = {"regular": ("ph", "Phosphor"), "fill": ("ph-fill", "Phosphor-Fill")}


def used_icons():
    text = "".join(p.read_text(errors="ignore") for p in
                   [ROOT / "build.py", ROOT / "assets/js/site.js", *ROOT.glob("**/index.html")])
    names = set(re.findall(r"\bph-([a-z0-9]+(?:-[a-z0-9]+)*)", text))
    return sorted(names - {"fill"})


def main():
    names = used_icons()
    css = [(ROOT / "assets/fonts/fonts.css").read_text()]
    for style, (cls, font) in STYLES.items():
        src = urllib.request.urlopen(f"{BASE}/{style}/style.css").read().decode()
        codes = {}
        for n in names:
            m = re.search(rf"\.{re.escape(cls)}\.ph-{re.escape(n)}:before\s*\{{\s*content:\s*\"\\([0-9a-f]+)\"", src)
            if m:
                codes[n] = m.group(1)
        raw = ROOT / f"assets/fonts/{font}.full.woff2"
        if not raw.exists():
            raw.write_bytes(urllib.request.urlopen(f"{BASE}/{style}/{font}.woff2").read())
        out = ROOT / f"assets/fonts/{font}.woff2"
        subprocess.run([sys.executable, "-m", "fontTools.subset", str(raw), "--unicodes=" + ",".join("U+" + c for c in codes.values()),
                        "--flavor=woff2", "--layout-features=*", f"--output-file={out}"], check=True)
        sel = ".ph" if style == "regular" else ".ph-fill"
        css.append(f"@font-face {{ font-family: '{font}'; src: url(../fonts/{font}.woff2) format('woff2'); font-weight: normal; font-style: normal; font-display: block; }}\n"
                   f"{sel} {{ font-family: '{font}' !important; speak: never; font-style: normal; font-weight: normal; font-variant: normal; text-transform: none; line-height: 1;"
                   f" -webkit-font-smoothing: antialiased; -moz-osx-font-smoothing: grayscale; display: inline-block; }}\n")
        css.append("".join(f'.{cls}.ph-{n}:before {{ content: "\\{c}"; }}\n' for n, c in sorted(codes.items())))
        missing = sorted(set(names) - set(codes))
        print(f"{style}: {len(codes)} icons, {out.stat().st_size} bytes" + (f"  (not in this style: {len(missing)})" if missing else ""))
    (ROOT / "assets/css/vendor.css").write_text("/* generated by vendor_assets.py */\n" + "".join(css))


if __name__ == "__main__":
    main()
